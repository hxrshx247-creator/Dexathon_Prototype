// Icon names come from labels.ts (lucide-react names). Unknown names fall back to a plain circle.
const ICONS: Record<string, LucideIcon> = {
  ArrowLeft,
  ArrowRight,
  Building2,
  Check,
  CircleAlert,
  Circle,
  CircleCheck,
  CircleDashed,
  CircleEllipsis,
  Clock,
  Copy,
  Download,
  FileText,
  FileWarning,
  GraduationCap,
  Hash,
  HeartPulse,
  Home: House,
  House,
  Inbox,
  LifeBuoy,
  Mail,
  MessageSquare,
  MessageSquarePlus,
  Paperclip,
  Phone,
  Plus,
  Receipt,
  Scale,
  Send,
  StickyNote,
  Upload,
  X,
};

export function Icon({ name, size = 18 }: { name?: string; size?: number }) {
  const Cmp = (name && ICONS[name]) || Circle;
  return <Cmp size={size} strokeWidth={1.9} aria-hidden="true" focusable="false" />;
}
